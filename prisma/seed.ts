async function main() {
  const replaceProducts = process.argv.includes("--replace-products");

  const mesasCount = await prisma.mesa.count();
  if (mesasCount === 0) {
    await prisma.mesa.createMany({
      data: Array.from({ length: 10 }, (_, idx) => ({
        numero: idx + 1,
        ativa: true,
      })),
    });
    console.log("Mesas 1 a 10 criadas.");
  } else {
    console.log("Mesas já existem — seed ignorado.");
  }

  if (replaceProducts) {
    await prisma.produto.deleteMany();
  }

  const produtosCount = await prisma.produto.count();
  if (produtosCount === 0) {
    await prisma.produto.createMany({
      data: CARDAPIO_OFICIAL.map((item) => ({
        ...item,
        ativo: true,
      })),
    });
    console.log(`${CARDAPIO_OFICIAL.length} produtos do cardápio oficial criados.`);
  } else {
    console.log("Produtos já existem — seed ignorado (use --replace-products para recriar).");
  }
}

main()
  .catch((error) => {
    console.error("Erro ao rodar seed:", error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
